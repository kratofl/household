export const dictionaries = { de, en } as const
export const supportedLocales = ["de", "en"] as const

export type Locale = (typeof supportedLocales)[number]
export type TranslationKey = keyof typeof de

export function isLocale(value: string | null | undefined): value is Locale {
  return supportedLocales.includes(value as Locale)
}

export function translate(
  locale: Locale,
  key: TranslationKey,
  values: Record<string, string | number> = {},
) {
  const template = dictionaries[locale][key] ?? dictionaries.de[key] ?? key

  return template.replace(/\{(\w+)\}/g, (match, valueKey) => {
    const value = values[valueKey]
    return value === undefined ? match : String(value)
  })
}

/** Bound translate() for one locale, as passed to view components. */
export type Translator = (
  key: TranslationKey,
  values?: Record<string, string | number>,
) => string
